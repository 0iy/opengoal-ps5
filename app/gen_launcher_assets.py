# Embeds the launcher artwork (art/launcher) as C arrays.
import os, sys
src = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'art', 'launcher') + os.sep
out = sys.argv[1]
names = ['bg1.jpg', 'bg2.jpg', 'bg3.jpg', 'logo1.png', 'logo2.png', 'logo3.png']
with open(out, 'w') as f:
    f.write('// generated by gen_launcher_assets.py - do not edit\n#include <cstddef>\n#include "ps5launcher.h"\n')
    for n in names:
        d = open(src + n, 'rb').read()
        v = n.replace('.', '_')
        f.write('static const unsigned char %s[] = {%s};\n' % (v, ','.join(str(b) for b in d)))
    f.write('const Ps5Asset kPs5Assets[] = {\n')
    for n in names:
        v = n.replace('.', '_')
        f.write('  {"%s", %s, sizeof(%s)},\n' % (n, v, v))
    f.write('};\nconst int kPs5AssetCount = %d;\n' % len(names))
