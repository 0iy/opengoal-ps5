#!/usr/bin/env python3
"""Generate ogapp/src/import_probe.c: a table of every imported symbol of the linked app.

At startup the app logs the entries whose address is 0 (imports the console's libc/kernel does not
export), which are the calls that would jump to NULL.
"""
import os
import subprocess

APP = os.path.expanduser("~/ogapp")
PIE = f"{APP}/build/llvm-pie.elf"
out = subprocess.run(["llvm-nm-18", "-D", "--undefined-only", PIE], capture_output=True, text=True).stdout.splitlines()
names = sorted({line.split()[-1].split("@")[0] for line in out if line.split()})
names = [n for n in names if n.replace("_", "a").isalnum() and not n.startswith("sceKernelDebug")]
src = ["// generated by gen_import_probe.py - do not edit", "#include <stddef.h>",
       'void ps5_log(const char*, ...) __asm__("_Z7ps5_logPKcz");']
for i, n in enumerate(names):
    src.append(f'extern char probe_sym_{i}[] __asm__("{n}") __attribute__((weak));')
src.append("void ps5_probe_imports(void) {")
src.append("  static const struct { const char* name; const void* addr; } t[] = {")
for i, n in enumerate(names):
    src.append(f'    {{"{n}", (const void*)probe_sym_{i}}},')
src.append("  };")
src.append("  int missing = 0;")
src.append("  char all[900]; size_t used = 0; all[0] = 0;")
src.append("  for (size_t i = 0; i < sizeof t / sizeof t[0]; ++i)")
src.append('    if (!t[i].addr) { ++missing; for (const char* c = t[i].name; *c && used < 880; ++c) all[used++] = *c; all[used++] = 0x20; all[used] = 0; }')
src.append('  ps5_log("MISSING IMPORTS: %s", all);')
src.append('  ps5_log("import probe: %d of %d imports unresolved", missing, (int)(sizeof t / sizeof t[0]));')
src.append("}")
path = f"{APP}/src/import_probe.c"
open(path, "w").write("\n".join(src) + "\n")
print(f"{len(names)} imports -> {path}")
