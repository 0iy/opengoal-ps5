#!/usr/bin/env python3
"""Generate ps5shim/gl_table.c: name -> address of every gl* entry point exported by libPS5OpenGL.a.

eglGetProcAddress on the PS5 does not return core entry points, but glad (used by the engine) asks the
SDL shim for every one by name. The shim falls back to this table.
"""
import os
import subprocess

LIBDIR = os.path.expanduser("~/gl/ps5-opengl-sdk-1.0.0/sdk/lib")
LIBS = [os.path.join(LIBDIR, n) for n in ("libglapi_bridge.a", "libps5_opengl_core33.a")]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ps5shim", "gl_table.c")

names = set()
for lib in LIBS:
    out = subprocess.run(["llvm-nm-18", "--defined-only", "-g", lib], capture_output=True, text=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in ("T", "W", "i") and parts[2].startswith("gl") and parts[2][2:3].isupper():
            names.add(parts[2])
# Only entry points the engine's glad loader asks for (references to others would need SDK import stubs).
import re
glad_src = open(os.path.expanduser("~/jak/third-party/glad/src/glad.c"), encoding="utf-8", errors="replace").read()
wanted = set(re.findall(r'"(gl[A-Z][A-Za-z0-9_]*)"', glad_src))
names = sorted(n for n in names if n in wanted)
src = ["// generated by gen_gl_table.py - do not edit", "#include <stddef.h>", "#include <string.h>"]
for i, n in enumerate(names):
    src.append(f'extern char gl_fn_{i}[] __asm__("{n}");  // strong: pulls the entry point out of the archive')
src.append("static const struct { const char* name; const void* addr; } kTable[] = {")
for i, n in enumerate(names):
    src.append(f'  {{"{n}", (const void*)gl_fn_{i}}},')
src.append("};")
src.append("const void* ps5_gl_lookup(const char* name) {")
src.append("  size_t lo = 0, hi = sizeof kTable / sizeof kTable[0];")
src.append("  while (lo < hi) {")
src.append("    size_t mid = (lo + hi) / 2;")
src.append("    int c = strcmp(name, kTable[mid].name);")
src.append("    if (c == 0) return kTable[mid].addr;")
src.append("    if (c < 0) hi = mid; else lo = mid + 1;")
src.append("  }")
src.append("  return NULL;")
src.append("}")
open(OUT, "w").write("\n".join(src) + "\n")
print(f"{len(names)} gl entry points -> {OUT}")
